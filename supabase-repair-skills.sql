-- ============================================================
-- ความถนัดของช่าง (ช่างคนไหนดูแลหมวดไหน)
--
-- เดิมมอบหมายงานต้องจำเอาเองว่างานรถให้ใคร งานเครื่องจักรให้ใคร
-- เก็บเป็นข้อมูลแทนการฝังชื่อในโค้ด เพราะคนเข้าออก/เปลี่ยนหน้าที่ได้
-- แก้ได้จากแดชบอร์ด ไม่ต้องรอแก้โค้ด
--
-- skills = หมวดที่ถนัด คั่นด้วยจุลภาค · เว้นว่าง = รับได้ทุกหมวด
-- หมวดที่มีในระบบ: รถขนส่ง · เครนรถขนส่ง · รถในโรงงาน · รถไฟ · เครน · เครื่องจักร
--
-- ของนี้เป็นแค่ "ตัวช่วยแนะนำ" ไม่ได้ล็อกสิทธิ์
-- ช่างคนอื่นยังรับงานข้ามหมวดได้ถ้าจำเป็น (คนลา/งานด่วน)
--
-- รันใน Supabase -> SQL Editor
-- ============================================================

alter table repair_staff add column if not exists skills text;

-- ตั้งค่าตามที่ใช้จริง: งานรถและเครนรถ -> ช่างหน่อย · งานอื่น -> ช่างเอก
-- หัวหน้าช่างเว้นว่างไว้ = เห็นว่าถนัดทุกหมวด
update repair_staff set skills = 'รถขนส่ง,เครนรถขนส่ง,รถในโรงงาน,รถไฟ'
 where site = 'banglen' and name = 'ช่างหน่อย';

update repair_staff set skills = 'เครน,เครื่องจักร'
 where site = 'banglen' and name = 'ช่างเอก';

select name, role, coalesce(skills,'(ทุกหมวด)') as ถนัด
from repair_staff
where site = 'banglen' and active and role in ('tech','head')
order by sort_order;
