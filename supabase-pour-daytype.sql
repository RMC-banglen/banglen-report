-- ============================================================
-- ประเภทวัน ในรายงานการผลิตรายวัน (pour_daily)
--
-- เดิม % ผลิตได้จริง หารด้วย "วันที่มีผลิต" ที่พิมพ์มาจากชีทรายเดือน
-- วันที่โรงงานเปิดแต่ไม่ได้ผลิต (ไม่มีคิว/ตัดสินใจหยุดเอง) ก็หลุดออกจากตัวหารไปด้วย
-- % เลยสวยเกินจริง เพราะนับเฉพาะวันที่ผลิตได้
--
-- แยกเป็น 3 แบบ
--   0 / ว่าง = ผลิตตามปกติ      -> นับเป็นวันทำงาน (เข้าตัวหาร)
--   1        = วันหยุดบริษัท     -> ไม่นับ ตัดออกจากตัวหาร
--   2        = หยุดเอง           -> นับเป็นวันทำงาน (เข้าตัวหาร) ผลิต 0 ก็ต้องรับไป
--
-- เดือนไหนยังไม่ได้ระบุประเภทวันเลย ระบบใช้ค่าเดิมจากชีทรายเดือนเหมือนเดิม
-- ตัวเลขเก่าจะไม่เปลี่ยนเองจนกว่าจะเริ่มกรอก
--
-- รันใน Supabase -> SQL Editor
-- ============================================================

alter table pour_daily add column if not exists day_type smallint;

comment on column pour_daily.day_type is '0/null=ผลิตปกติ · 1=วันหยุดบริษัท (ไม่คิด%) · 2=หยุดเอง (คิด%)';

-- ดูว่าแต่ละเดือนระบุประเภทวันไปแล้วแค่ไหน
select to_char(d,'YYYY-MM') as เดือน,
       count(*)                                         as วันที่กรอก,
       count(*) filter (where coalesce(day_type,0)=1)   as หยุดบริษัท,
       count(*) filter (where day_type=2)               as หยุดเอง,
       count(*) filter (where coalesce(day_type,0)<>1)  as วันทำงานที่ใช้หาร
from pour_daily
group by 1
order by 1 desc;
